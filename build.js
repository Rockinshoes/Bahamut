/*
 * build.js - packs the whole game into ONE file, play.html.
 *
 * Why: some places (phone file previewers, email attachments, quick-look
 * windows) open a single HTML file on its own and cannot load the separate
 * style.css, js/ and assets/ files next to it. play.html has everything inside it,
 * including any card art in assets/cards/ (.webp or .png).
 *
 * Run:  node build.js
 * Re-run it after you change index.html, style.css, js/*.js or the art.
 * (The "Generate card art" GitHub Action runs it for you.)
 */
'use strict';
var fs = require('fs');
var path = require('path');

function read(p) { return fs.readFileSync(path.join(__dirname, p), 'utf8'); }

// Card and enemy art, as data URLs the game can show without separate files.
function artBundle() {
  var dir = path.join(__dirname, 'assets', 'cards');
  var art = {}, bytes = 0;
  if (!fs.existsSync(dir)) { return { art: art, bytes: 0 }; }
  fs.readdirSync(dir).sort().forEach(function (file) {
    var m = file.match(/^([a-z0-9-]+)\.(webp|png)$/);
    if (!m) { return; }
    if (art[m[1]] && m[2] === 'png') { return; } // prefer .webp when both exist
    var data = fs.readFileSync(path.join(dir, file));
    bytes += data.length;
    art[m[1]] = 'data:image/' + m[2] + ';base64,' + data.toString('base64');
  });
  return { art: art, bytes: bytes };
}

var html = read('index.html');

html = html.replace('<link rel="stylesheet" href="style.css">', function () {
  return '<style>\n' + read('style.css') + '</style>';
});

var bundle = artBundle();
var artScript = Object.keys(bundle.art).length
  ? '<script>\nwindow.CARD_ART = ' + JSON.stringify(bundle.art) + ';\n</script>\n  '
  : '';

html = html.replace(/<script src="([^"]+)"><\/script>/g, function (match, src) {
  var code = read(src);
  if (code.indexOf('</script') !== -1) { throw new Error(src + ' contains </script, cannot inline'); }
  return (src === 'js/ui.js' ? artScript : '') + '<script>\n' + code + '</script>';
});

var banner = '<!-- GENERATED by build.js from index.html, style.css, js/*.js and assets/cards. Edit those, then run: node build.js -->\n';
fs.writeFileSync(path.join(__dirname, 'play.html'), html.replace('<!doctype html>', '<!doctype html>\n' + banner));
console.log('Wrote play.html (' + Math.round(Buffer.byteLength(html) / 1024) + ' KB, ' +
  Object.keys(bundle.art).length + ' art images, ' + Math.round(bundle.bytes / 1024) + ' KB of art)');
