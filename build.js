/*
 * build.js - packs the whole game into ONE file, play.html.
 *
 * Why: some places (phone file previewers, email attachments, quick-look
 * windows) open a single HTML file on its own and cannot load the separate
 * style.css and js/ files next to it. play.html has everything inside it.
 *
 * Run:  node build.js
 * Re-run it after you change any of index.html, style.css or js/*.js.
 */
'use strict';
var fs = require('fs');
var path = require('path');

function read(p) { return fs.readFileSync(path.join(__dirname, p), 'utf8'); }

var html = read('index.html');

html = html.replace('<link rel="stylesheet" href="style.css">', function () {
  return '<style>\n' + read('style.css') + '</style>';
});

html = html.replace(/<script src="([^"]+)"><\/script>/g, function (match, src) {
  var code = read(src);
  if (code.indexOf('</script') !== -1) { throw new Error(src + ' contains </script, cannot inline'); }
  return '<script>\n' + code + '</script>';
});

var banner = '<!-- GENERATED by build.js from index.html, style.css and js/*.js. Edit those, then run: node build.js -->\n';
fs.writeFileSync(path.join(__dirname, 'play.html'), html.replace('<!doctype html>', '<!doctype html>\n' + banner));
console.log('Wrote play.html (' + Math.round(html.length / 1024) + ' KB)');
